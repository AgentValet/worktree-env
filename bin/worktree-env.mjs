#!/usr/bin/env node
// worktree-env: give every git worktree the env files from your main checkout.
// Zero dependencies. Node 18+.

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const HELP = `worktree-env: share env files across git worktrees

Usage:
  worktree-env [link]   Link env files from the main checkout into this worktree
  worktree-env status   Show what each env file in this worktree points at
  worktree-env help

Options:
  --agent     Write filtered copies holding only the keys in agent.keep
              (for worktrees an AI coding agent works in)
  --copy      Copy instead of symlinking
  --force     Replace env files that already exist here
  --dry-run   Print what would happen, change nothing

Config (optional): .worktree-env.json at the repo root
  {
    "files": [".env", "apps/api/.env"],
    "agent": { "keep": ["AGENTVALET_*", "NODE_ENV", "PORT"] }
  }
Without "files", every gitignored .env, .env.* and .dev.vars file in the
main checkout is used (except templates like .env.example and backups
like .env.bak). Listing "files" also skips the scan, which is faster in
big repos.
WORKTREE_ENV_AGENT=1 turns on --agent.`;

const GENERATED = "# generated by worktree-env --agent: edit the main checkout's copy, not this one";

function git(cwd, ...args) {
  return execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], maxBuffer: 64 * 1024 * 1024 }).trim();
}

export function findCheckouts(cwd) {
  const here = path.resolve(git(cwd, "rev-parse", "--show-toplevel"));
  const commonDir = path.resolve(cwd, git(cwd, "rev-parse", "--git-common-dir"));
  const main = path.dirname(commonDir);
  return { here, main };
}

function loadConfig(main) {
  const file = path.join(main, ".worktree-env.json");
  if (!fs.existsSync(file)) return {};
  try {
    return JSON.parse(fs.readFileSync(file, "utf8"));
  } catch (err) {
    throw new Error(`.worktree-env.json is not valid JSON: ${err.message}`);
  }
}

const ENV_NAME = /^(\.env(\..+)?|\.dev\.vars(\..+)?)$/;
const TEMPLATE = /\.(example|sample|template)$/;
const BACKUP = /\.(bak|backup|old|orig)(\.|$)/;

export function discoverEnvFiles(main) {
  const out = git(main, "ls-files", "--others", "--ignored", "--exclude-standard", "--",
    ":(glob)**/.env", ":(glob)**/.env.*", ":(glob)**/.dev.vars", ":(glob)**/.dev.vars.*");
  return out
    .split("\n")
    .filter(Boolean)
    .filter((f) => !f.split("/").includes("node_modules"))
    .filter((f) => ENV_NAME.test(path.posix.basename(f)) && !TEMPLATE.test(f) && !BACKUP.test(f))
    .sort();
}

function isIgnored(cwd, rel) {
  try {
    execFileSync("git", ["check-ignore", "-q", "--no-index", rel], { cwd, stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
}

function globToRegex(pattern) {
  const escaped = pattern.replace(/[.+^${}()|[\]\\]/g, "\\$&").replace(/\*/g, ".*").replace(/\?/g, ".");
  return new RegExp(`^${escaped}$`);
}

// Keeps only the KEY=value entries whose key matches one of `keep`.
// Comments and blank lines are dropped; quoted multi-line values are kept whole.
export function filterEnv(text, keep) {
  const patterns = keep.map(globToRegex);
  const lines = text.split(/\r?\n/);
  const kept = [];
  for (let i = 0; i < lines.length; i++) {
    const m = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_.-]*)\s*=\s*(.*)$/.exec(lines[i]);
    if (!m) continue;
    const entry = [lines[i]];
    const quote = m[2][0];
    if ((quote === '"' || quote === "'") && !m[2].slice(1).includes(quote)) {
      while (i + 1 < lines.length) {
        entry.push(lines[++i]);
        if (lines[i].includes(quote)) break;
      }
    }
    if (patterns.some((p) => p.test(m[1]))) kept.push(...entry);
  }
  return kept;
}

function describe(target) {
  const st = fs.lstatSync(target, { throwIfNoEntry: false });
  if (!st) return "missing";
  if (st.isSymbolicLink()) return `link -> ${fs.readlinkSync(target)}`;
  const head = fs.readFileSync(target, "utf8").split(/\r?\n/, 1)[0];
  return head === GENERATED ? "agent copy" : "file";
}

export function link({ cwd = process.cwd(), agent = false, copy = false, force = false, dryRun = false, log = console.log } = {}) {
  const { here, main } = findCheckouts(cwd);
  if (here === main) {
    log("This is the main checkout: it holds the originals, nothing to link.");
    return [];
  }
  const config = loadConfig(main);
  const files = config.files ?? discoverEnvFiles(main);
  const keep = config.agent?.keep ?? [];
  if (agent && keep.length === 0) {
    throw new Error('--agent needs "agent": { "keep": [...] } in .worktree-env.json');
  }
  if (files.length === 0) log(`No env files found in ${main}.`);

  const results = [];
  for (const rel of files) {
    const source = path.join(main, rel);
    const target = path.join(here, rel);
    const report = (action) => {
      results.push({ file: rel, action });
      log(`${action.padEnd(9)} ${rel}`);
    };

    if (!fs.existsSync(source)) { report("no-source"); continue; }
    if (!isIgnored(here, rel)) { report("unignored"); continue; }

    const existing = fs.lstatSync(target, { throwIfNoEntry: false });
    const refreshable = agent && existing && describe(target) === "agent copy";
    if (existing && !force && !refreshable) {
      const ok = existing.isSymbolicLink() && path.resolve(path.dirname(target), fs.readlinkSync(target)) === source;
      report(ok && !agent ? "ok" : "exists");
      continue;
    }
    if (dryRun) { report(agent ? "would-filter" : copy ? "would-copy" : "would-link"); continue; }

    fs.mkdirSync(path.dirname(target), { recursive: true });
    if (existing) fs.rmSync(target);

    if (agent) {
      const kept = filterEnv(fs.readFileSync(source, "utf8"), keep);
      fs.writeFileSync(target, [GENERATED, ...kept, ""].join("\n"), { mode: 0o600 });
      report("filtered");
    } else if (copy) {
      fs.copyFileSync(source, target);
      report("copied");
    } else {
      try {
        fs.symlinkSync(source, target, "file");
        report("linked");
      } catch (err) {
        if (err.code !== "EPERM" && err.code !== "EACCES") throw err;
        fs.copyFileSync(source, target);
        report("copied");
        log("          (symlinks need Developer Mode on Windows; copied instead)");
      }
    }
  }

  if (results.some((r) => r.action === "exists")) log("\nFiles marked 'exists' were left alone. Use --force to replace them.");
  if (results.some((r) => r.action === "unignored")) log("\nFiles marked 'unignored' are not gitignored here, so they were skipped to keep secrets out of commits.");
  return results;
}

export function status({ cwd = process.cwd(), log = console.log } = {}) {
  const { here, main } = findCheckouts(cwd);
  const config = loadConfig(main);
  const files = config.files ?? discoverEnvFiles(main);
  for (const rel of files) log(`${rel}: ${describe(path.join(here, rel))}`);
}

function main(argv) {
  const flags = new Set(argv.filter((a) => a.startsWith("--")));
  const [command = "link"] = argv.filter((a) => !a.startsWith("--"));
  const known = new Set(["--agent", "--copy", "--force", "--dry-run", "--help"]);
  for (const f of flags) if (!known.has(f)) throw new Error(`Unknown option ${f}`);

  if (command === "help" || flags.has("--help")) return console.log(HELP);
  if (command === "status") return status();
  if (command !== "link") throw new Error(`Unknown command ${command}. Try: worktree-env help`);
  link({
    agent: flags.has("--agent") || process.env.WORKTREE_ENV_AGENT === "1",
    copy: flags.has("--copy"),
    force: flags.has("--force"),
    dryRun: flags.has("--dry-run"),
  });
}

const invokedDirectly = process.argv[1] && fs.realpathSync(process.argv[1]) === fs.realpathSync(new URL(import.meta.url));
if (invokedDirectly) {
  try {
    main(process.argv.slice(2));
  } catch (err) {
    console.error(`worktree-env: ${err.message}`);
    process.exit(1);
  }
}
